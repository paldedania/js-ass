let x;
let y = null;

console.log("x =", x);
console.log("y =", y);
console.log("typeof x:", typeof x);
console.log("typeof y:", typeof y);
console.log("x == y:", x == y);
console.log("x === y:", x === y);

// A variable is undefined when it has been declared but no value was assigned,
// or when a requested property/value does not exist.
// null is used intentionally to represent an empty or missing value.
