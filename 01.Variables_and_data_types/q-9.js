// Use a meaningful default and name instead of an uninitialized x.
let count = 0;

// Split unrelated declarations and give each value a descriptive name.
let firstValue = 1;
let secondValue = 2;
let thirdValue = 3;

// PI is a constant, so use const and the conventional uppercase name.
const PI = 3.14159;

// Use camelCase for multi-word variable names.
let userName = "John";
let itemCount = 0;

console.log({ count, firstValue, secondValue, thirdValue, PI, userName, itemCount });
