let x;
let y = null;

console.log("x =", x);
console.log("y =", y);

console.log("typeof x:", typeof x);
console.log("typeof y:", typeof y);

console.log("x == y:", x == y);
console.log("x === y:", x === y);

// A variable is undefined when we don't assign any value to it.

// A variable is null when we assign the keyword `null` as it's value.